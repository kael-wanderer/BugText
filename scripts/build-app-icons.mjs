// Generates the app-icon carousel assets from the logo concept artboards.
//
// Source: docs/design/logo-concepts/project/<File>.dc.html. Each artboard holds
// one <symbol id="ic" viewBox="0 0 1024 1024">. NOTE: docs/ is gitignored, so
// these sources are local-only; the OUTPUTS below are committed:
//   - src/settings-screen/app-icons.ts   (preview SVG markup, carousel order)
//   - src-tauri/icons/dock/<id>.png      (512x512 Dock PNGs, not for page-bug)
// page-bug is the bundle icon, so the Dock is reset to it (no PNG needed).
//
// Add a concept: add its id to APP_ICON_IDS in src/settings.ts, add a row to
// CONCEPTS below, add the id to the allowlist in src-tauri/src/dock_icon.rs,
// then run `npm run icons:app`.

import { execFileSync } from "node:child_process";
import { copyFileSync, mkdirSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join, resolve } from "node:path";

const root = resolve(import.meta.dirname, "..");
const sourceDir = join(root, "docs/design/logo-concepts/project");
const dockDir = join(root, "src-tauri/icons/dock");
const outTs = join(root, "src/settings-screen/app-icons.ts");

const CONCEPTS = [
  { id: "page-bug", file: "PageBug", name: "Page Bug" },
  { id: "cursor-ladybug", file: "Main", name: "Cursor Ladybug" },
  { id: "hash-beetle", file: "HashBeetle", name: "Hash Beetle" },
  { id: "bt-lettermark", file: "Lettermark", name: "bT Lettermark" },
  { id: "line-bug", file: "LineBug", name: "Line Bug" },
  { id: "markdown-bug", file: "MarkdownBug", name: "Markdown Bug" },
  { id: "b-wings", file: "BWings", name: "B Wings" },
  { id: "nib-bug", file: "NibBug", name: "Nib Bug" },
  { id: "firefly-cursor", file: "FireflyCursor", name: "Firefly Cursor" },
  { id: "pixel-bug", file: "PixelBug", name: "Pixel Bug" },
];

function symbolBody(file) {
  const html = readFileSync(join(sourceDir, `${file}.dc.html`), "utf8");
  const match = html.match(/<symbol id="ic" viewBox="0 0 1024 1024">([\s\S]*?)<\/symbol>/);
  if (!match) throw new Error(`${file}: no <symbol id="ic"> found`);
  return match[1].trim().replace(/\s*\n\s*/g, "");
}

function standaloneSvg(id, body) {
  const crisp = id === "pixel-bug" ? ' shape-rendering="crispEdges"' : "";
  return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 1024 1024"${crisp}>${body}</svg>`;
}

const icons = CONCEPTS.map(({ id, file, name }) => ({ id, name, svg: standaloneSvg(id, symbolBody(file)) }));

const ts = `// GENERATED by scripts/build-app-icons.mjs — do not edit by hand.
// Static markup from the logo concept artboards (no user data).

import type { AppIconId } from "../settings";

export const APP_ICONS: ReadonlyArray<{ id: AppIconId; name: string; svg: string }> = [
${icons.map((i) => `  { id: ${JSON.stringify(i.id)}, name: ${JSON.stringify(i.name)}, svg: ${JSON.stringify(i.svg)} },`).join("\n")}
];
`;
writeFileSync(outTs, ts);

mkdirSync(dockDir, { recursive: true });
const tmp = mkdtempSync(join(tmpdir(), "bugtext-app-icons-"));
try {
  for (const icon of icons) {
    if (icon.id === "page-bug") continue;
    const svgPath = join(tmp, `${icon.id}.svg`);
    const outDir = join(tmp, icon.id);
    writeFileSync(svgPath, icon.svg);
    execFileSync("npx", ["tauri", "icon", svgPath, "-o", outDir], { cwd: root, stdio: "ignore" });
    copyFileSync(join(outDir, "icon.png"), join(dockDir, `${icon.id}.png`));
    console.log(`dock/${icon.id}.png`);
  }
} finally {
  rmSync(tmp, { recursive: true, force: true });
}
console.log("wrote src/settings-screen/app-icons.ts");
